"""Generate sw.js: a service worker that precaches every file RAHA needs, so the deployed site
keeps working with the internet switched off after one visit (Constraint 1).

python scripts/make_sw.py   (re-run after adding files; bump happens automatically via content hash)
"""
import hashlib
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMPORTMAP = {"three": "vendor/three/build/three.module.min.js", "three/addons/": "vendor/three/addons/"}


def resolve(spec, base_dir):
    if spec.startswith("three/addons/"):
        return IMPORTMAP["three/addons/"] + spec[len("three/addons/"):]
    if spec == "three":
        return IMPORTMAP["three"]
    if spec.startswith("."):
        return os.path.normpath(os.path.join(base_dir, spec)).replace("\\", "/")
    return None


def walk_imports(entry, seen):
    if entry in seen or not os.path.exists(os.path.join(ROOT, entry)):
        return
    seen.add(entry)
    if not entry.endswith(".js"):
        return
    src = open(os.path.join(ROOT, entry), encoding="utf-8").read()
    for spec in re.findall(r"(?:import|export)[^'\"]*?from\s*['\"]([^'\"]+)['\"]", src) + re.findall(r"import\(\s*['\"]([^'\"]+)['\"]\s*\)", src):
        r = resolve(spec, os.path.dirname(entry))
        if r:
            walk_imports(r, seen)


files = set()
walk_imports("src/app.js", files)
walk_imports("src/netguard.js", files)
files |= {"index.html", "src/style.css"}
for d in ("data", "vendor/fonts"):
    for dp, _, fns in os.walk(os.path.join(ROOT, d)):
        for fn in fns:
            files.add(os.path.relpath(os.path.join(dp, fn), ROOT).replace("\\", "/"))
files = sorted(f for f in files if os.path.exists(os.path.join(ROOT, f)))
h = hashlib.sha256()
for f in files:
    h.update(f.encode())
    h.update(open(os.path.join(ROOT, f), "rb").read())
version = h.hexdigest()[:12]
urls = ["./"] + ["./" + f for f in files]
sw = f"""// RAHA offline service worker (generated by scripts/make_sw.py, do not edit by hand)
const CACHE = 'raha-{version}';
const PRECACHE = {json.dumps(urls, indent=0)};
self.addEventListener('install', (e) => {{ e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', (e) => {{ e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener('fetch', (e) => {{
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{ if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }} return res; }})));
}});
self.addEventListener('message', (e) => {{ if (e.data === 'raha-cache-status') caches.open(CACHE).then((c) => c.keys()).then((ks) => e.source.postMessage({{ type: 'raha-cache-status', cached: ks.length, total: PRECACHE.length, version: CACHE }})); }});
"""
open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8").write(sw)
print(f"sw.js: {len(urls)} files precached, cache raha-{version}")
